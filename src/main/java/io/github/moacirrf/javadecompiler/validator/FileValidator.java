package io.github.moacirrf.javadecompiler.validator;

import static io.github.moacirrf.javadecompiler.files.FileSystemHelper.CLASSFILE_BINARY_NAME;
import static io.github.moacirrf.javadecompiler.files.FileSystemHelper.CLASSFILE_ROOT;
import static java.util.Objects.isNull;
import static java.util.Objects.nonNull;

import org.openide.awt.StatusDisplayer;
import org.openide.filesystems.FileObject;

public final class FileValidator {

    private static final String INVALID_FILE = "Invalid file.";
    private static final String ACCEPTED_FILES = "Only class files are accepted.";

    /**
     * Folder where netbeans stores the generated java stubs of class files
     * without source code (javap like output), eg:
     * ~/.cache/netbeans/&lt;version&gt;/index/&lt;slot&gt;/java/&lt;release&gt;/gensrc
     */
    private static final String GENSRC_FOLDER = "gensrc";

    public static boolean validate(FileObject file) {
        if (isDecompilable(file)) {
            return true;
        }
        StatusDisplayer.getDefault().setStatusText(isNull(file) ? INVALID_FILE : ACCEPTED_FILES);
        return false;
    }

    /**
     * Silent check (no status message) used to decide if the decompiler menu
     * should be shown. Only class files, and java files generated by netbeans
     * on the gensrc cache folder (class file without source), are decompilable.
     *
     * @param file file to check
     * @return true when the file can be decompiled
     */
    public static boolean isDecompilable(FileObject file) {
        if (isNull(file)) {
            return false;
        }
        String extension = file.getExt().toLowerCase();
        if ("class".equals(extension)) {
            return true;
        }
        if ("java".equals(extension) && isInGeneratedSources(file)) {
            return true;
        }
        return isClassOriginFromJar(file);
    }

    private static boolean isInGeneratedSources(FileObject file) {
        String path = file.getPath();
        return path.contains("/".concat(GENSRC_FOLDER).concat("/"))
                || path.startsWith(GENSRC_FOLDER.concat("/"));
    }

    /**
     * When a class file is opened on netbeans editor, the default action is
     * show a JAVAP output, but the address of a original class file and jar is
     * stored on attribute. The generated java stubs on gensrc folder also
     * carry these attributes.
     *
     * @param file
     * @return
     */
    private static boolean isClassOriginFromJar(FileObject file) {
        return nonNull(file.getAttribute(CLASSFILE_ROOT))
                && nonNull(file.getAttribute(CLASSFILE_BINARY_NAME));
    }

    private FileValidator() {
    }
}
